import shutil
import subprocess
import sys
from importlib.metadata import PackageNotFoundError, distribution
from importlib.util import find_spec
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent
RESOURCE_DIR = ROOT / "src" / "resources"
ICONS_DIR = RESOURCE_DIR / "icons"
QRC_PATH = RESOURCE_DIR / "resources.qrc"
PY_PATH = RESOURCE_DIR / "resources.py"


def build() -> None:
    icon_files = sorted(
        path for path in ICONS_DIR.iterdir()
        if path.is_file() and path.suffix.lower() in {".png", ".svg"}
    )
    entries = [
        f'    <file alias="{escape(path.name)}">icons/{escape(path.name)}</file>'
        for path in icon_files
    ]
    qrc_content = [
        '<!DOCTYPE RCC><RCC version="1.0">',
        '  <qresource prefix="/icons">',
        *entries,
        "  </qresource>",
        "</RCC>",
        "",
    ]
    QRC_PATH.write_text("\n".join(qrc_content), encoding="utf-8")

    pyside6_rcc = shutil.which("pyside6-rcc")
    if not pyside6_rcc:
        candidate = Path(sys.executable).with_name(
            "pyside6-rcc.exe" if sys.platform == "win32" else "pyside6-rcc"
        )
        if candidate.is_file():
            pyside6_rcc = str(candidate)

    compiler = shutil.which("pyrcc6")
    if pyside6_rcc:
        command = [pyside6_rcc, str(QRC_PATH), "-o", str(PY_PATH)]
    elif compiler:
        command = [compiler, str(QRC_PATH), "-o", str(PY_PATH)]
    elif find_spec("PySide6.pyrcc_main") is not None:
        command = [
            sys.executable,
            "-m",
            "PySide6.pyrcc_main",
            str(QRC_PATH),
            "-o",
            str(PY_PATH),
        ]
    else:
        try:
            qt_distribution = distribution("qt6-applications")
        except PackageNotFoundError:
            qt_distribution = None

        rcc_path = None
        if qt_distribution is not None:
            rcc_files = [
                path for path in qt_distribution.files or ()
                if path.as_posix().endswith("Qt/bin/rcc.exe")
                or path.as_posix().endswith("Qt/bin/rcc")
            ]
            if rcc_files:
                candidate = qt_distribution.locate_file(rcc_files[0])
                if candidate.is_file():
                    rcc_path = str(candidate)

        if rcc_path:
            command = [
                rcc_path,
                "--generator",
                "python",
                str(QRC_PATH),
                "-o",
                str(PY_PATH),
            ]
        else:
            icon_paths = ",\n".join(
                f"    {path.name!r}: RESOURCE_DIR / 'icons' / {path.name!r}"
                for path in icon_files
            )
            PY_PATH.write_text(
                "# Generated by build_assets.py; SVGs are loaded from disk.\n"
                "from pathlib import Path\n\n"
                "RESOURCE_DIR = Path(__file__).resolve().parent\n"
                f"ICON_PATHS = {{\n{icon_paths}\n}}\n",
                encoding="utf-8",
            )
            print(
                "Qt resource compiler not found; created resources.py with file-based "
                "icon paths (resources are not embedded). Install pyrcc6 or "
                "qt6-applications to embed them.",
                file=sys.stderr,
            )
            return

    subprocess.run(command, check=True, cwd=ROOT)
    generated = PY_PATH.read_text(encoding="utf-8")
    generated = generated.replace("from PySide6 import QtCore", "from PySide6 import QtCore")
    PY_PATH.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    build()
