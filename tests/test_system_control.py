import os
import sys
import unittest
from unittest.mock import MagicMock, patch

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from src.utils import system_control
from src.utils.system_control import ControlSystem

FAKE_APPS = [
    ("Telegram", r"C:\Users\user\AppData\Roaming\Telegram Desktop\Telegram.exe"),
    ("Деинсталлировать Telegram", r"C:\Users\user\AppData\Roaming\Telegram Desktop\unins000.exe"),
    ("Steam", r"D:\Steam\Steam.exe"),
    ("Steam Support Center", "http://support.steampowered.com/"),
    ("Visual Studio Code", "Microsoft.VisualStudioCode"),
    ("Paint", "Microsoft.Paint_8wekyb3d8bbwe!App"),
    ("Uninstall Node.js", "Microsoft.AutoGenerated.{56DB442F}"),
]


class ResolverTests(unittest.TestCase):
    def setUp(self):
        self.patches = [
            patch.object(ControlSystem, "_start_apps_cache", None),
            patch.object(ControlSystem, "_apps_cache", None),
        ]
        for p in self.patches:
            p.start()
        self.query = patch.object(
            ControlSystem, "_query_start_apps", return_value=list(FAKE_APPS)
        )
        self.query.start()

    def tearDown(self):
        self.query.stop()
        for p in self.patches:
            p.stop()

    def test_uninstallers_are_filtered(self):
        apps = ControlSystem._get_start_apps()
        names = [name for name, _ in apps]
        self.assertIn("Telegram", names)
        self.assertIn("Steam", names)
        self.assertNotIn("Деинсталлировать Telegram", names)
        self.assertNotIn("Uninstall Node.js", names)

    def test_telegram_resolves_to_app_not_uninstaller(self):
        name, app_id = ControlSystem._find_start_app("telegram")
        self.assertEqual(name, "Telegram")
        self.assertTrue(app_id.endswith("Telegram.exe"))

    def test_exact_name_beats_link(self):
        name, app_id = ControlSystem._find_start_app("steam")
        self.assertEqual(app_id, r"D:\Steam\Steam.exe")

    def test_case_and_exe_suffix_ignored(self):
        name, app_id = ControlSystem._find_start_app("TELEGRAM.EXE")
        self.assertEqual(name, "Telegram")

    def test_unknown_app_returns_none(self):
        self.assertIsNone(ControlSystem._find_start_app("нет такого приложения"))

    def test_available_apps_have_no_uninstallers(self):
        apps = ControlSystem.get_available_apps()
        self.assertIn("Telegram", apps)
        self.assertFalse(any("unins" in name.lower() for name in apps))
        self.assertFalse(any("деинстал" in name.lower() for name in apps))

    def test_expired_cache_returns_stale_and_refreshes_in_background(self):
        ControlSystem._apps_cache = ["Old App"]
        ControlSystem._apps_cache_time = 0.0  # просрочен

        with patch.object(ControlSystem, "_refresh_apps_async") as refresh:
            apps = ControlSystem.get_available_apps()

        self.assertEqual(apps, ["Old App"])
        refresh.assert_called_once()


class OpenCloseTests(unittest.TestCase):
    def setUp(self):
        patch.object(ControlSystem, "_start_apps_cache", None).start()
        patch.object(
            ControlSystem, "_query_start_apps", return_value=list(FAKE_APPS)
        ).start()

    def tearDown(self):
        patch.stopall()

    def test_open_resolves_and_never_calls_appopener(self):
        with patch.object(system_control.os.path, "exists", return_value=False), \
             patch.object(system_control.subprocess, "Popen") as popen, \
             patch.object(system_control.AppOpener, "open") as appopener_open:
            ControlSystem.open_application("telegram")

        appopener_open.assert_not_called()
        args = popen.call_args[0][0]
        self.assertEqual(args[0], "explorer.exe")
        self.assertIn("Telegram.exe", args[1])

    def test_open_falls_back_to_appopener_for_unknown(self):
        with patch.object(system_control.AppOpener, "open") as appopener_open:
            ControlSystem.open_application("whatever")

        appopener_open.assert_called_once()
        self.assertEqual(appopener_open.call_args[0][0], "whatever")

    def test_close_terminates_resolved_exe(self):
        process = MagicMock()
        process.info = {"name": "Telegram.exe"}
        with patch.object(
            system_control.psutil, "process_iter", return_value=[process]
        ), patch.object(system_control.psutil, "wait_procs", return_value=([], [])), \
             patch.object(system_control.AppOpener, "close") as appopener_close:
            ControlSystem.close_application("telegram")

        process.terminate.assert_called_once()
        appopener_close.assert_not_called()

    def test_close_uwp_falls_back_to_appopener(self):
        with patch.object(system_control.AppOpener, "close") as appopener_close:
            ControlSystem.close_application("paint")

        appopener_close.assert_called_once()


class UninstallerPatternTests(unittest.TestCase):
    def test_pattern(self):
        self.assertTrue(system_control._is_uninstaller("Деинсталлировать Telegram", "x"))
        self.assertTrue(system_control._is_uninstaller("Telegram", r"C:\x\unins000.exe"))
        self.assertTrue(system_control._is_uninstaller("Uninstall Node.js", "x"))
        self.assertFalse(system_control._is_uninstaller("Telegram", r"C:\x\Telegram.exe"))
        self.assertFalse(system_control._is_uninstaller("Paint", "Microsoft.Paint!App"))


